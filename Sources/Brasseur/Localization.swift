import Foundation

/// Langue de l'interface : celle de macOS (français si l'OS est en français, anglais sinon).
/// Pas de réglage : c'est le choix de langue du système (ou de l'app dans Réglages Système) qui décide.
enum L10n {
    static let isFrench: Bool = {
        let lang = Bundle.main.preferredLocalizations.first ?? Locale.preferredLanguages.first ?? "en"
        return lang.hasPrefix("fr")
    }()
    static let locale = Locale(identifier: isFrench ? "fr" : "en")
}

/// Traduit un texte écrit en français (la clé) vers la langue de l'interface.
func tr(_ key: String) -> String {
    L10n.isFrench ? key : (englishStrings[key] ?? key)
}

/// Variante avec arguments au format printf (%@ pour un texte, %d pour un entier).
func tr(_ key: String, _ args: CVarArg...) -> String {
    String(format: tr(key), locale: L10n.locale, arguments: args)
}

/// Singulier ou pluriel selon la langue (en français, 0 et 1 sont au singulier).
func trn(_ count: Int, _ singular: String, _ plural: String) -> String {
    let useSingular = L10n.isFrench ? count <= 1 : count == 1
    return tr(useSingular ? singular : plural, count)
}

